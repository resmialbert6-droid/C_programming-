int main() {
    int age = 29;
    float marks = 60.6f;
    double pi = 3.14159;
    char grade = 'p';
    char name[] = "ruby";

    printf("Name: %s\n", name);
    printf("Age: %d\n", age);
    printf("Marks: %f\n", marks);
    printf("Pi: %lf\n", pi);
    printf("Grade: %c\n", grade);

    return 0;
}
